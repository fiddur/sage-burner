import type { Answers } from '@sage-burner/shared'
import type { SQL } from 'drizzle-orm'
import type { SQLiteColumn } from 'drizzle-orm/sqlite-core'

import { accountRoles, applicationStatuses, formQuestionTypes, paymentStatuses } from '@sage-burner/shared'
import { sql } from 'drizzle-orm'
import { check, index, integer, primaryKey, sqliteTable, text, uniqueIndex } from 'drizzle-orm/sqlite-core'

/**
 * `column IN (...)`, built from a vocabulary in `@sage-burner/shared`.
 *
 * Drizzle's `{ enum: [...] }` only narrows the TypeScript type — it emits no
 * constraint, so without this a bad value reaching the database by any path
 * other than the API would be stored happily. Generating the CHECK from the
 * same constant the API validates against is what actually keeps the two from
 * drifting.
 */
const oneOf = (column: SQLiteColumn, values: readonly string[]): SQL => {
  // Must be `sql.raw`, not interpolation: `sql`${value}`` produces a bound
  // parameter, and a `?` placeholder inside a CHECK constraint is meaningless
  // DDL. These values are compile-time constants from our own source, but the
  // quote-doubling keeps that from being load-bearing.
  const literals = values.map((value) => `'${value.replaceAll("'", "''")}'`).join(', ')
  return sql`${column} in (${sql.raw(literals)})`
}

/**
 * Database schema.
 *
 * Conventions:
 * - Ids are TEXT UUIDs generated by the application, never autoincrementing
 *   integers — an id in a URL should leak neither record counts nor the
 *   existence of neighbours.
 * - Dates and timestamps are TEXT in ISO 8601 form, exactly as they cross the
 *   API boundary. SQLite has no date type, and storing the wire format means
 *   there is no conversion layer to get wrong (and the file stays readable).
 * - Timestamps are supplied by the application rather than by SQL defaults, so
 *   tests can inject a fixed clock.
 * - Enum columns are TEXT constrained by the vocabularies in
 *   `@sage-burner/shared`, so the database and the API cannot drift apart.
 */

/** A single burn. Never assume there is only one — the whole point is recurrence. */
export const event = sqliteTable(
  'event',
  {
    id: text('id').notNull(),
    name: text('name').notNull(),
    slug: text('slug').notNull().unique(),
    start_date: text('start_date').notNull(),
    end_date: text('end_date').notNull(),
    welcome_markdown: text('welcome_markdown').notNull().default(''),
    member_cap: integer('member_cap').notNull(),
    created_at: text('created_at').notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.id] }),
    // Mirrors `withEventDateOrder` in the shared schemas. Dates are fixed-width
    // ISO, so a string comparison is chronological here.
    check('event_date_order_check', sql`${table.end_date} >= ${table.start_date}`),
    check('event_member_cap_check', sql`${table.member_cap} > 0`),
  ],
)

/**
 * One question on an event's application form.
 *
 * Rows, not code: organisers retune these between burns, so adding, editing or
 * reordering a question must never require a redeploy.
 */
export const formQuestion = sqliteTable(
  'form_question',
  {
    id: text('id').notNull(),
    event_id: text('event_id')
      .notNull()
      .references(() => event.id, { onDelete: 'cascade' }),
    // Not unique: reordering swaps positions, and a transient collision
    // mid-swap must not be rejected by the database.
    order: integer('order').notNull(),
    type: text('type', { enum: formQuestionTypes }).notNull(),
    label: text('label').notNull(),
    help_text: text('help_text'),
    required: integer('required', { mode: 'boolean' }).notNull().default(false),
    /** Reserved for future select/radio types; no question type consumes it yet. */
    options: text('options', { mode: 'json' }).$type<string[] | null>(),
  },
  (table) => [
    primaryKey({ columns: [table.id] }),
    index('form_question_event_order_idx').on(table.event_id, table.order),
    check('form_question_type_check', oneOf(table.type, formQuestionTypes)),
    check('form_question_order_check', sql`${table.order} >= 0`),
    // SQLite has no boolean type, so without this the column accepts 7.
    check('form_question_required_check', sql`${table.required} in (0, 1)`),
  ],
)

/** A membership application submitted through the public form. */
export const application = sqliteTable(
  'application',
  {
    id: text('id').notNull(),
    event_id: text('event_id')
      .notNull()
      .references(() => event.id, { onDelete: 'cascade' }),
    /**
     * Answers keyed by `form_question.id`.
     *
     * The type is imported, not restated: `Answers` is a *partial* record,
     * because an unanswered optional question is absent at runtime. Writing
     * `Record<string, string | boolean>` here would not be assignable from what
     * the API layer validates, and the insert would need a cast to compile.
     */
    answers: text('answers', { mode: 'json' }).$type<Answers>().notNull(),
    status: text('status', { enum: applicationStatuses }).notNull().default('pending'),
    applicant_name: text('applicant_name').notNull(),
    applicant_contact: text('applicant_contact').notNull(),
    submitted_at: text('submitted_at').notNull(),
    decided_at: text('decided_at'),
  },
  (table) => [
    primaryKey({ columns: [table.id] }),
    index('application_event_status_idx').on(table.event_id, table.status),
    check('application_status_check', oneOf(table.status, applicationStatuses)),
  ],
)

/** A login identity. Password and passkeys both hang off this. */
export const account = sqliteTable(
  'account',
  {
    id: text('id').notNull(),
    /**
     * Always lowercase — enforced by the CHECK below, not merely intended.
     *
     * SQLite's UNIQUE on TEXT uses BINARY collation, so on its own it would
     * make `admin@example.org` and `Admin@Example.org` two different accounts
     * for one human, each with its own passkeys, roles and memberships.
     * Requiring the stored form to be lowercase also guarantees an exact-match
     * lookup on a lowercased input can never miss a row.
     */
    email: text('email').notNull().unique(),
    /** Nullable: a passkey-only account is legitimate. */
    password_hash: text('password_hash'),
    created_at: text('created_at').notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.id] }),
    check('account_email_lowercase_check', sql`${table.email} = lower(${table.email})`),
  ],
)

/** A registered WebAuthn credential. An account may have several, or none. */
export const passkey = sqliteTable(
  'passkey',
  {
    id: text('id').notNull(),
    account_id: text('account_id')
      .notNull()
      .references(() => account.id, { onDelete: 'cascade' }),
    credential_id: text('credential_id').notNull().unique(),
    public_key: text('public_key').notNull(),
    /** Signature counter, for cloned-authenticator detection. */
    counter: integer('counter').notNull().default(0),
    created_at: text('created_at').notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.id] }),
    index('passkey_account_idx').on(table.account_id),
    check('passkey_counter_check', sql`${table.counter} >= 0`),
  ],
)

/** Coarse access level. No fine-grained permissions in v1. */
export const accountRole = sqliteTable(
  'account_role',
  {
    account_id: text('account_id')
      .notNull()
      .references(() => account.id, { onDelete: 'cascade' }),
    role: text('role', { enum: accountRoles }).notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.account_id, table.role] }),
    check('account_role_check', oneOf(table.role, accountRoles)),
  ],
)

/**
 * A single-use invitation to join an event.
 *
 * Both membership paths converge here: approving an application mints one with
 * `application_id` set, and an admin direct invite mints one with it null.
 */
export const inviteToken = sqliteTable(
  'invite_token',
  {
    id: text('id').notNull(),
    /**
     * SHA-256 of the invite token, never the token itself.
     *
     * The token is CSPRNG-random and unguessable, shown once in the link the
     * admin copies, and then only its digest is kept. Storing it in the clear
     * would make the SQLite file the secret: a leaked backup, or a stray copy
     * of the Docker volume, would hand out every unexpired invite verbatim.
     *
     * Lookup is by exact match on the digest, so this costs nothing
     * structurally. A plain SHA-256 is sufficient and no KDF is needed —
     * unguessable input means there is no dictionary to run.
     */
    token_hash: text('token_hash').notNull().unique(),
    event_id: text('event_id')
      .notNull()
      .references(() => event.id, { onDelete: 'cascade' }),
    /** Null for an admin-created direct invite with no application behind it. */
    application_id: text('application_id').references(() => application.id, { onDelete: 'set null' }),
    expires_at: text('expires_at').notNull(),
    /**
     * Stamped on redemption, for display and auditing.
     *
     * This is a record of redemption, not the thing preventing a second one —
     * inserting a member against an already-stamped token is accepted here.
     * `member_invite_token_idx` is what actually enforces single use.
     */
    used_at: text('used_at'),
    created_by: text('created_by')
      .notNull()
      .references(() => account.id),
  },
  (table) => [primaryKey({ columns: [table.id] }), index('invite_token_event_idx').on(table.event_id)],
)

/**
 * A person's participation in one specific burn.
 *
 * Scoped to `(event, account)`: the same human attending three burns has three
 * rows, each with its own payment state, allergies and arrival dates.
 */
export const member = sqliteTable(
  'member',
  {
    id: text('id').notNull(),
    event_id: text('event_id')
      .notNull()
      .references(() => event.id, { onDelete: 'cascade' }),
    account_id: text('account_id')
      .notNull()
      .references(() => account.id),
    name: text('name').notNull(),
    contact: text('contact').notNull(),
    allergies_notes: text('allergies_notes'),
    arrival_date: text('arrival_date'),
    departure_date: text('departure_date'),
    /**
     * Free text, not an enum. The options differ per event and per site, so
     * organisers must be able to add one without a deploy.
     */
    lodging: text('lodging'),
    shift_preference: text('shift_preference'),
    notes: text('notes'),
    /** Admin-set only. Members can read their own status but never write it. */
    payment_status: text('payment_status', { enum: paymentStatuses }).notNull().default('unpaid'),
    payment_date: text('payment_date'),
    /**
     * The invite this membership was redeemed from.
     *
     * Deliberately **not** constrained to match `event_id`: nothing here stops
     * an invite minted for the autumn burn being redeemed into the spring one.
     * Doing that in the schema needs a unique index on `invite_token(event_id,
     * id)` plus a composite foreign key, and unlike double redemption — which
     * is a check-then-act race the application cannot win alone — this is
     * ordinary application logic, so the redemption path (#17) owns it.
     */
    invite_token_id: text('invite_token_id')
      .notNull()
      .references(() => inviteToken.id),
  },
  (table) => [
    primaryKey({ columns: [table.id] }),
    // One membership per person per burn.
    uniqueIndex('member_event_account_idx').on(table.event_id, table.account_id),
    // What actually makes an invite single-use. Stamping `used_at` in the
    // application is a check-then-act race with nothing underneath it, and the
    // index above only stops the *same* account joining twice — so without
    // this, a forwarded invite link lets a second person redeem it and quietly
    // breaks member_cap accounting, which is sized against invites issued.
    uniqueIndex('member_invite_token_idx').on(table.invite_token_id),
    // Mirrors `withMemberStayOrder` in the shared schemas.
    check(
      'member_stay_order_check',
      sql`${table.arrival_date} is null or ${table.departure_date} is null
          or ${table.departure_date} >= ${table.arrival_date}`,
    ),
    // No separate index on event_id alone: SQLite uses the leftmost prefix of
    // member_event_account_idx for that, so one would only add write cost.
    // Note this covers one direction only — "which burns is this person a
    // member of?" filters on account_id and falls back to a scan. Left that
    // way deliberately: at ~42 members across a handful of events the scan is
    // free, and an index would cost a write on every member update.
    check('member_payment_status_check', oneOf(table.payment_status, paymentStatuses)),
  ],
)

/**
 * A "dream" — a member-offered workshop, ceremony or happening.
 *
 * Named `session` per the original data model. Unrelated to login sessions,
 * which are cookie-based and have no table.
 *
 * A null time slot means offered-but-not-yet-scheduled, which is the normal
 * state right up until the burn — not an error.
 */
export const session = sqliteTable(
  'session',
  {
    id: text('id').notNull(),
    event_id: text('event_id')
      .notNull()
      .references(() => event.id, { onDelete: 'cascade' }),
    title: text('title').notNull(),
    host_member_id: text('host_member_id')
      .notNull()
      .references(() => member.id, { onDelete: 'cascade' }),
    description: text('description').notNull().default(''),
    time_slot_start: text('time_slot_start'),
    time_slot_end: text('time_slot_end'),
    location: text('location'),
  },
  (table) => [
    primaryKey({ columns: [table.id] }),
    index('session_event_slot_idx').on(table.event_id, table.time_slot_start),
    // Mirrors `withValidTimeSlot`: a slot is both ends or neither. The
    // ordering half of that rule is not expressible here — comparing ISO
    // timestamps needs instant semantics, not SQLite string comparison — so it
    // stays in the Zod schema. Noted so the asymmetry does not read as an
    // oversight.
    check(
      'session_slot_whole_check',
      sql`(${table.time_slot_start} is null) = (${table.time_slot_end} is null)`,
    ),
  ],
)

